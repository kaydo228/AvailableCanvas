#!/usr/bin/env bash
# commit-msg: правки общего шва обязаны идти коммитом с префиксом `contract:`.
#
# Правило записано в CLAUDE.md с первого дня и за неделю не выполнено ни разу —
# ни одним из двоих. Причина простая: его нечем было заметить. Хуки проверяли
# типы и формат, но не то, какой файл в каком коммите. Это и есть механизм.
#
# Шов — модель данных и стор: их меняют только вдвоём, потому что расхождение
# здесь разъезжается у обоих сразу.
#
# Запрет мягкий по одной причине: бывает правка шва, которая не меняет контракт
# (комментарий, перенос строки). Поэтому хук не блокирует, а требует явного
# подтверждения через `CONTRACT_OK=1 git commit`. Молча пройти нельзя,
# сознательно — можно.
set -euo pipefail

message_file="${1:?путь к файлу сообщения коммита}"
seam='^(src/shared/types/document\.ts|src/shared/store/)'

staged=$(git diff --cached --name-only --diff-filter=ACMR | grep -E "$seam" || true)
[ -z "$staged" ] && exit 0

if head -1 "$message_file" | grep -Eq '^contract:'; then
  exit 0
fi

if [ "${CONTRACT_OK:-}" = "1" ]; then
  echo "contract-check: правка шва без префикса пропущена по CONTRACT_OK=1." >&2
  exit 0
fi

cat >&2 <<MSG

  ✗ Коммит трогает общий шов, но не помечен префиксом contract:

    $(printf '%s\n' "$staged" | sed 's/^/    /')

  CLAUDE.md, раздел «Контракт между зонами»: модель данных и стор меняются
  только парой и коммитом с префиксом contract:. Это не формальность —
  27 августа именно этот файл дал самый тяжёлый конфликт при сведении веток.

  Что делать:
    • переименовать коммит: contract: <что меняется в контракте>
    • или, если контракт не меняется (комментарий, формат):
      CONTRACT_OK=1 git commit ...

MSG
exit 1
