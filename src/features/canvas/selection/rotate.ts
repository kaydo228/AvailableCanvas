/**
 * Правило поворота: приведение угла и вращение точки вокруг центра.
 *
 * Живёт рядом с `resize.ts` по той же причине: стор описывает, ЧТО делает
 * действие, а геометрия — это отдельное знание, которое хочется проверять
 * без поднятия стора.
 */

export interface Point {
  x: number;
  y: number;
}

/** Полный оборот. Числом 360 в коде не повторяется — их легко разъехать. */
export const FULL_TURN = 360;

/**
 * Угол в диапазон [0, 360).
 *
 * 370° и −10° — один и тот же поворот, и хранить их по-разному значит завести
 * две записи для одного состояния: инспектор покажет «−10», экспорт посчитает
 * рамку от «350», а сравнение углов двух узлов соврёт. Диапазон выбран
 * [0, 360), а не (−180, 180]: он совпадает с тем, как угол читают люди
 * («повернуть на 270»), и не даёт двух подписей нулю.
 *
 * Нечисловой угол — это 0, а не «оставить как было». Так же поступают
 * `clampOpacity` (мусор → 1) и починка документа на входе
 * (`persistence/repair.ts`: `finite(node.rotation, 0)`): вместо мусора
 * подставляется нейтральное значение, потому что NaN в `rotation` уезжает
 * в матрицу Konva и гасит узел целиком — он перестаёт рисоваться и ловиться
 * мышью, а причина по картинке не видна.
 */
export function normalizeAngle(degrees: number): number {
  if (!Number.isFinite(degrees)) return 0;

  const turned = degrees % FULL_TURN;
  // `+ 0` убирает минус-ноль: `-0 % 360` даёт `-0`, а `Object.is(-0, 0)` —
  // ложь, и такой угол расходится с нулём в сравнениях и в снимках истории.
  return (turned < 0 ? turned + FULL_TURN : turned) + 0;
}

/**
 * Точка, повёрнутая вокруг центра.
 *
 * Konva вращает узел вокруг его `x, y`, то есть вокруг левого верхнего угла
 * (та же математика в `export/lib/bounds.ts`). Поэтому поворот НАБОРА вокруг
 * общего центра — это две правки на узел: угол прибавляется, а левый верхний
 * угол переезжает по окружности. Одной прибавки угла мало — узлы разъедутся,
 * каждый провернувшись вокруг себя.
 */
export function rotatePoint(point: Point, center: Point, degrees: number): Point {
  const radians = (degrees * Math.PI) / 180;
  const cos = Math.cos(radians);
  const sin = Math.sin(radians);

  const dx = point.x - center.x;
  const dy = point.y - center.y;

  return {
    x: center.x + dx * cos - dy * sin,
    y: center.y + dx * sin + dy * cos,
  };
}
