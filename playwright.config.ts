import { defineConfig } from '@playwright/test';

export default defineConfig({
  testDir: './e2e',
  // Ожидание по умолчанию — 5 с, и его не хватало под полной нагрузкой:
  // файлы идут параллельно, dev-сервер Vite компилирует модули по первому
  // запросу, а половина проверок ждёт круга через IndexedDB. На одиночном
  // прогоне те же сценарии проходили всегда. Это не «повтор до зелёного»
  // (retries здесь намеренно нет), а честный запас на медленный первый круг.
  expect: { timeout: 15_000 },
  use: { baseURL: 'http://localhost:5173', actionTimeout: 15_000 },

  projects: [
    {
      // Обычный набор: всё, кроме замера производительности.
      name: 'e2e',
      testIgnore: /perf\.spec\.ts/,
    },
    {
      /**
       * Замер производительности — отдельным проектом и строго в один поток.
       *
       * Сначала он лежал в общем наборе и падал примерно раз на четыре полных
       * прогона: fps проседал с 55 до 51 при пороге 50. Причина не в доске —
       * рядом работали тринадцать браузерных контекстов на той же машине.
       * Это ровно то, о чём написано в самом замере: если рядом что-то
       * молотит процессор, меришь машину, а не доску. Бенчмарк, делящий
       * процессор с чужой нагрузкой, не измеряет ничего.
       *
       * Поэтому: `npm run e2e` — функциональные сценарии, детерминированные;
       * `npm run perf` — замер, в один поток, отдельной командой. Расширять
       * пороги было бы проще и было бы враньём: они и так стоят выше факта.
       */
      name: 'perf',
      testMatch: /perf\.spec\.ts/,
      fullyParallel: false,
      workers: 1,
    },
  ],

  webServer: {
    command: 'npm run dev',
    url: 'http://localhost:5173',
    reuseExistingServer: true,
  },
});
